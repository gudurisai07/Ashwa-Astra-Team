import TagList from './TagList';

export function Block({ title, children }) {
  return (
    <section className="card block">
      <h3>{title}</h3>
      {children}
    </section>
  );
}

export function BulletList({ items }) {
  if (!Array.isArray(items) || !items.length) return <span className="muted">Nothing reported</span>;
  return (
    <ul className="bullets">
      {items.map((x, i) => (
        <li key={i}>{typeof x === 'string' ? x : JSON.stringify(x)}</li>
      ))}
    </ul>
  );
}

export function Skills({ title, items, tone }) {
  return (
    <Block title={title}>
      <TagList items={items} tone={tone} />
    </Block>
  );
}

export function Disclaimer({ result }) {
  if (!result) return null;
  return (
    <p className="muted small">
      Generated by {result.model || 'Gemini'}. {result.disclaimer || 'AI output is decision support only.'}
    </p>
  );
}

/** Shared "run AI" panel: shows the stored result, a run button, loading and error state. */
export function RunBar({ onRun, busy, label, hasResult }) {
  return (
    <div className="runbar">
      <button className="btn btn-primary" onClick={onRun} disabled={busy} style={{minWidth:160}}>
        {busy ? '⏳ Gemini is working…' : hasResult ? `🔄 Re-run ${label}` : `🚀 Run ${label}`}
      </button>
      {busy && <span className="spinner" aria-hidden="true" />}
    </div>
  );
}
